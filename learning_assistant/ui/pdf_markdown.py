"""Qt Markdown with protected local formulas and validated PDF citations."""

from html import escape
import re
from uuid import uuid4

from PySide6.QtGui import QFontInfo, QImage, QTextCharFormat, QTextCursor, QTextDocument, QTextFormat


class _MarkdownDocument(QTextDocument):
    def loadResource(self, resource_type, url):
        # Model-supplied Markdown images must not read files or fetch URLs.
        return QImage()


def render_markdown(text, replacements=()):
    """Render Markdown, then restore trusted inline HTML outside code spans.

    Each replacement is (start, end, render_callback). The callback is lazy so
    code samples neither typeset math nor register clickable PDF citations.
    """
    if not text:
        return ""
    prefix = "PDFINLINE" + uuid4().hex
    parts, protected, end = [], [], 0
    for start, stop, render in sorted(replacements, key=lambda item: item[0]):
        token = prefix + str(len(protected)) + "END"
        parts.extend((text[end:start], token))
        protected.append((token, text[start:stop], render))
        end = stop
    parts.append(text[end:])
    document = _MarkdownDocument()
    document.setMarkdown("".join(parts), QTextDocument.MarkdownFeature.MarkdownDialectGitHub
                         | QTextDocument.MarkdownFeature.MarkdownNoHTML)

    fragments = []
    block = document.begin()
    while block.isValid():
        iterator = block.begin()
        while not iterator.atEnd():
            fragment = iterator.fragment()
            if fragment.isValid():
                fragments.append((fragment.position(), fragment.length(), fragment.charFormat()))
            iterator += 1
        block = block.next()
    for position, length, format in reversed(fragments):
        cursor = QTextCursor(document)
        cursor.setPosition(position)
        cursor.setPosition(position + length, QTextCursor.MoveMode.KeepAnchor)
        if format.isImageFormat():
            label = format.property(QTextFormat.Property.ImageAltText) or "[图片]"
            cursor.insertText(str(label), QTextCharFormat())
        elif format.isAnchor():
            # Only citations generated by the application become links.
            format.setAnchor(False)
            format.setAnchorHref("")
            format.setFontUnderline(False)
            format.clearProperty(QTextFormat.Property.ForegroundBrush)
            cursor.setCharFormat(format)

    html = re.search(r"<body[^>]*>(.*)</body>", document.toHtml(), re.DOTALL).group(1)
    for token, source, render in protected:
        cursor = document.find(token)
        format = cursor.charFormat()
        # Fenced code has an explicit platform-dependent fixed-width family
        # (Courier New on Windows), without always setting FontFixedPitch.
        literal = (cursor.isNull() or format.fontFixedPitch()
                   or bool(format.fontFamilies() and QFontInfo(format.font()).fixedPitch()))
        html = html.replace(token, escape(source) if literal else render())
    return html
